import { cleanupOutdatedCaches, precacheAndRoute } from "workbox-precaching"
import { clientsClaim } from "workbox-core"
import { NavigationRoute, registerRoute } from "workbox-routing"
import { NetworkFirst } from "workbox-strategies"


import { initializeApp } from "firebase/app"
import { getMessaging, onBackgroundMessage } from "firebase/messaging/sw"

// Where the build really lives. The worker is served from /hrms/sw.js (so it
// can control /hrms), but Vite writes the precache entries RELATIVE
// ("assets/x.js"), and Workbox resolves those against the worker's URL — so
// they became /hrms/assets/x.js, which Frappe answers with the app's HTML page.
// Re-based here onto the real files (review of 6a1f33315).
const ASSET_BASE = "/assets/hrms/frontend/"

function rebased(entries) {
	const out = entries.map((entry) => {
		const url = typeof entry === "string" ? entry : entry.url
		const revision = typeof entry === "string" ? null : entry.revision
		return { url: url.startsWith("/") || /^https?:/.test(url) ? url : ASSET_BASE + url, revision }
	})
	console.info("[sw] precache entries re-based onto", ASSET_BASE, out.length)
	return out
}

// Use the precache manifest generated by Vite
const PRECACHE = rebased(self.__WB_MANIFEST)
precacheAndRoute(PRECACHE)

// Clean up old caches
cleanupOutdatedCaches()

// The app page itself (alpha.12 C1). Frappe renders /hrms per user — it carries
// the CSRF token and boot — so it is not in the build's precache, and the
// installed app opened offline to a browser error. Network first: online it is
// always fresh; offline the last good copy opens and the app's own offline
// banner says so. Only /hrms pages; Desk and the API are never touched.
registerRoute(
	new NavigationRoute(new NetworkFirst({ cacheName: "nadi-pages", networkTimeoutSeconds: 4 }), {
		allowlist: [/^\/hrms(\/|$)/],
	})
)

const jsonConfig = new URL(location).searchParams.get("config")

// Firebase config initialization
try {
	const firebaseApp = initializeApp(JSON.parse(jsonConfig))
	const messaging = getMessaging(firebaseApp)

	function isChrome() {
		return navigator.userAgent.toLowerCase().includes("chrome")
	}

	onBackgroundMessage(messaging, (payload) => {
		const notificationTitle = payload.data.title
		let notificationOptions = {
			body: payload.data.body || "",
		}
		if (payload.data.notification_icon) {
			notificationOptions["icon"] = payload.data.notification_icon
		}
		// Carry the URL on data for EVERY browser so the notificationclick
		// handler below can find it on a body tap. Non-Chrome additionally gets
		// an explicit action button.
		notificationOptions["data"] = {
			url: payload.data.click_action,
		}
		if (!isChrome() && payload.data.click_action) {
			notificationOptions["actions"] = [
				{
					action: payload.data.click_action,
					title: "View Details",
				},
			]
		}
		self.registration.showNotification(notificationTitle, notificationOptions)
	})

} catch (error) {
	console.log("Failed to initialize Firebase", error)
}

// Register for ALL browsers — this used to be Chrome-only, so on Firefox,
// Safari and Samsung Internet tapping the notification did nothing at all. A
// body tap carries no action and finds the URL on data; an action-button tap
// carries the URL as event.action.
//
// OUTSIDE the Firebase block (30 Sep 2026: a senior tapped an announcement and
// "nothing happens"): inside it, any failure to start messaging left no tap
// handler at all. And the open is kept alive with waitUntil; without it the
// browser may end the event before the window opens. An open Nadi window is
// reused and taken to the link rather than opening a second one.
self.addEventListener("notificationclick", (event) => {
	event.stopImmediatePropagation()
	event.notification.close()
	const url = (event.notification.data && event.notification.data.url) || event.action
	if (!url) return
	event.waitUntil(
		clients.matchAll({ type: "window", includeUncontrolled: true }).then((open) => {
			const nadi = open.find((client) => new URL(client.url).pathname.startsWith("/hrms"))
			if (nadi && "navigate" in nadi) {
				return nadi.navigate(url).then((client) => (client || nadi).focus())
			}
			return clients.openWindow(url)
		})
	)
})

// NOT skipWaiting() at module scope. That activated every new build the instant
// it installed and reloaded the page under whatever the employee was doing. The
// page asks while the app is hidden (src/data/swRegistration.js), and this
// listens for that one message.
self.addEventListener("message", (event) => {
	if (event.data && event.data.type === "SKIP_WAITING") {
		console.log("The page asked for the new version")
		self.skipWaiting()
	}
})

// `clientsClaim` stays: it decides which worker controls an ALREADY-OPEN page
// once one has activated; activation happens only while the app is hidden. It
// does not activate anything by itself.
clientsClaim()
console.log("Service Worker Initialized")
